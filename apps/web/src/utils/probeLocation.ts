/**
 * Probe locations are operator-chosen labels, most often an airport code. Known
 * codes get their country flag, anything else is shown as typed.
 */
export function locationFlag(location: string): string | null {
  const code = location.trim().toUpperCase();
  return FLAGS[code] ?? null;
}
